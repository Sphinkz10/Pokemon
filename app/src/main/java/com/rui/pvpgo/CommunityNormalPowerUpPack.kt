package com.rui.pvpgo

import com.rui.pvpgo.domain.InvestmentCostPack
import com.rui.pvpgo.domain.PowerUpStepCost
import com.rui.pvpgo.engine.InvestmentCostPackValidator

/**
 * Source-reviewed COMMUNITY reference for regular Pokémon power-ups, NOT an
 * authenticated live Pokémon GO game-master snapshot. Reviewed 2026-10-15.
 *
 * Sources:
 * https://www.poketools.com/pokemon-go-power-up-calculator
 * https://pokemongohub.net/post/guide/xl-candy-guide-how-to-get-power-up-costs-and-mechanics/
 * https://pokemongohub.net/post/guide/guide-to-power-up-costs-in-pokemon-go/
 *
 * Only covers existing, normal Pokémon at current species/form: power-ups
 * from levels 1 to 50. No evolutions, new moves, event costs, Lucky,
 * Shadow/Purified modifiers, exceptional species or Best Buddy levels.
 */
internal object CommunityNormalPowerUpPack {
    const val ID = "community-normal-powerup-2026-10-15"
    const val VERSION = "1"
    const val SOURCE_NAME = "PokeTools + Pokemon GO Hub (community)"
    const val SOURCE_VERSION = "checked-2026-10-15"
    const val REVIEWED_EPOCH_MS = 1792022400000L
    const val SOURCE_URL = "https://www.poketools.com/pokemon-go-power-up-calculator"
    const val CROSS_CHECK_URL =
        "https://pokemongohub.net/post/guide/xl-candy-guide-how-to-get-power-up-costs-and-mechanics/"
    // Independently pinned canonical hash; do not replace with pack.contentHashSha256.
    const val PINNED_HASH_SHA256 =
        "16ccf51ada8255c59ffbf23a235b6057064a291b29f1f89deaacbf40d964b7d9"

    /**
     * Half-level steps are generated by inclusive pre-power-up ranges. All
     * ranges are consecutive; the 1->40, 20->40 and 40->50 sums are tested.
     */
    private data class Band(
        val firstHalfLevel: Int,
        val lastHalfLevel: Int,
        val dust: Int,
        val candy: Int,
        val xl: Int = 0
    )

    private val bands = listOf(
        Band(2, 5, 200, 1), Band(6, 9, 400, 1),
        Band(10, 13, 600, 1), Band(14, 17, 800, 1),
        Band(18, 21, 1000, 1), Band(22, 25, 1300, 2),
        Band(26, 29, 1600, 2), Band(30, 33, 1900, 2),
        Band(34, 37, 2200, 2), Band(38, 41, 2500, 2),
        Band(42, 45, 3000, 3), Band(46, 49, 3500, 3),
        Band(50, 51, 4000, 3), Band(52, 53, 4000, 4),
        Band(54, 57, 4500, 4), Band(58, 61, 5000, 4),
        Band(62, 65, 6000, 6), Band(66, 69, 7000, 8),
        Band(70, 73, 8000, 10), Band(74, 77, 9000, 12),
        Band(78, 79, 10000, 15),
        Band(80, 81, 10000, 0, 10),
        Band(82, 83, 11000, 0, 10),
        Band(84, 85, 11000, 0, 12),
        Band(86, 87, 12000, 0, 12),
        Band(88, 89, 12000, 0, 15),
        Band(90, 91, 13000, 0, 15),
        Band(92, 93, 13000, 0, 17),
        Band(94, 95, 14000, 0, 17),
        Band(96, 97, 14000, 0, 20),
        Band(98, 99, 15000, 0, 20)
    )

    val steps: List<PowerUpStepCost> by lazy {
        bands.flatMap { band ->
            (band.firstHalfLevel..band.lastHalfLevel).map { n ->
                PowerUpStepCost(
                    fromLevel = n / 2.0,
                    toLevel = (n + 1) / 2.0,
                    stardust = band.dust,
                    candy = band.candy,
                    xlCandy = band.xl
                )
            }
        }
    }

    val pack: InvestmentCostPack by lazy {
        InvestmentCostPackValidator.build(
            id = ID,
            version = VERSION,
            sourceName = SOURCE_NAME,
            sourceVersion = SOURCE_VERSION,
            generatedAtEpochMs = REVIEWED_EPOCH_MS,
            powerUpSteps = steps,
            speciesCosts = emptyList(),
            evolutionCosts = emptyList()
        )
    }

    /**
     * Integrity and provenance check. An internally consistent *different*
     * pack is not this reviewed community reference.
     */
    fun authenticatedReference(): Boolean =
        steps.size == 98 &&
            steps.map { it.fromLevel }.distinct().size == 98 &&
            steps.mapIndexed { index, step -> step.fromLevel == 1.0 + index / 2.0 }.all { it } &&
            pack.id == ID && pack.version == VERSION &&
            pack.sourceName == SOURCE_NAME && pack.sourceVersion == SOURCE_VERSION &&
            pack.generatedAtEpochMs == REVIEWED_EPOCH_MS &&
            pack.contentHashSha256 == PINNED_HASH_SHA256 &&
            InvestmentCostPackValidator.validate(pack).isEmpty()

    /** Exception and form modifiers are deliberately not priced here. */
    fun isSupportedNormalPokemon(speciesId: String, form: String): Boolean =
        speciesId.isNotBlank() &&
            !speciesId.contains("eternatus", ignoreCase = true) &&
            !speciesId.contains("mega", ignoreCase = true) &&
            !speciesId.contains("primal", ignoreCase = true) &&
            !form.startsWith("Mega", ignoreCase = true) &&
            !form.startsWith("Primal", ignoreCase = true)

    const val LIMITATIONS =
        "Tabela comunitária consultada em 15/10/2026, não sincronizada com o jogo. " +
            "Estimativa apenas de power-ups para Pokémon normais, sem evoluções, ataques, " +
            "TMs, segundo ataque, eventos, formas especiais ou relevância no meta. " +
            "Confirma sempre os valores no Pokémon GO antes de gastar recursos."
}
